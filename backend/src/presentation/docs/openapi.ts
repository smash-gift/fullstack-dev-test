import { z } from 'zod';

import {
  errorResponseSchema,
  suggestMessagesResponseSchema,
} from '../validators/suggestions-response.schema.js';
import { suggestMessagesBodySchema } from '../validators/suggestions.schema.js';

export interface OpenApiInfo {
  readonly version: string;
}

/** JSON Schema as OpenAPI 3.0 expects it: the input side for requests. */
function requestSchema(schema: z.ZodType): unknown {
  return z.toJSONSchema(schema, { io: 'input', target: 'openapi-3.0' });
}

/** The output side for responses — where defaults are already applied. */
function responseSchema(schema: z.ZodType): unknown {
  return z.toJSONSchema(schema, { io: 'output', target: 'openapi-3.0', unrepresentable: 'any' });
}

function jsonContent(schema: unknown, example?: unknown): unknown {
  return { 'application/json': example === undefined ? { schema } : { schema, example } };
}

const DEGRADED_EXAMPLE = {
  data: {
    suggestions: [
      { id: 's1', text: 'Wishing you a wonderful day filled with everything you love.' },
      { id: 's2', text: 'Thinking of you today and hoping it brings you joy.' },
    ],
    source: 'fallback',
    model: null,
    degraded: true,
  },
  meta: {
    requestId: 'req_8f3c1a2b4d5e6f70',
    generatedAt: '2026-09-03T18:20:00.000Z',
    cached: false,
    reason: 'llm_timeout',
  },
};

/**
 * Builds the OpenAPI document from the schemas the API actually validates
 * with.
 *
 * Hand-written API documentation drifts from the code — not as a possibility
 * but as a matter of time, because the first field added without updating the
 * spec breaks the promise and nobody notices until a consumer complains. Here
 * a disagreement between what the API accepts and what it documents is not
 * possible: they are the same object, read two ways.
 *
 * Zod 4 emits JSON Schema natively (`z.toJSONSchema`), so this costs no extra
 * dependency — the generator library the plan named turned out to be work the
 * validation library already does.
 */
export function buildOpenApiDocument(info: OpenApiInfo): Record<string, unknown> {
  return {
    openapi: '3.0.3',
    info: {
      title: 'Gift Card Message Suggester',
      version: info.version,
      description:
        'Suggests short gift card messages for an occasion and a relationship.\n\n' +
        'When the language model is unavailable the API still answers `200` with ' +
        'curated messages and `degraded: true` — a request never fails because a ' +
        'third party did.',
    },
    // Relative, so "Try it out" calls whichever host is serving these docs
    // instead of a hostname baked in at build time.
    servers: [{ url: '/', description: 'This server' }],
    tags: [
      { name: 'Suggestions', description: 'Message generation' },
      { name: 'Health', description: 'Liveness' },
    ],
    paths: {
      '/api/v1/suggestions': {
        post: {
          tags: ['Suggestions'],
          summary: 'Generate gift card message suggestions',
          description:
            'Rate limited per IP. A blocked request never reaches the model, ' +
            'which is the point: it costs nothing.',
          requestBody: {
            required: true,
            content: jsonContent(requestSchema(suggestMessagesBodySchema), {
              occasion: 'birthday',
              relationship: 'friend',
              tone: 'warm',
              language: 'en',
              count: 3,
            }),
          },
          responses: {
            200: {
              description:
                'Suggestions generated. Check `data.degraded`: when true the model ' +
                'could not be used and the messages are curated fallbacks.',
              content: {
                'application/json': {
                  schema: responseSchema(suggestMessagesResponseSchema),
                  examples: {
                    generated: {
                      summary: 'Generated by the model',
                      value: {
                        data: {
                          suggestions: [
                            {
                              id: 's1',
                              text: 'Happy birthday! So glad the world got you in it.',
                            },
                            {
                              id: 's2',
                              text: 'Wishing you a year as bright and generous as you are.',
                            },
                            {
                              id: 's3',
                              text: 'Another trip around the sun, and still my favourite person to celebrate.',
                            },
                          ],
                          source: 'llm',
                          model: 'gpt-4o-mini',
                          degraded: false,
                        },
                        meta: {
                          requestId: 'req_8f3c1a2b4d5e6f70',
                          generatedAt: '2026-09-03T18:20:00.000Z',
                          cached: false,
                        },
                      },
                    },
                    degraded: {
                      summary: 'Model unavailable — curated fallback',
                      value: DEGRADED_EXAMPLE,
                    },
                  },
                },
              },
            },
            400: {
              description: 'The body failed validation, or was rejected by the input sanitiser.',
              content: jsonContent(responseSchema(errorResponseSchema), {
                error: {
                  code: 'VALIDATION_ERROR',
                  message: 'Invalid request body',
                  details: [{ field: 'occasion', issue: 'occasion must be at least 2 characters' }],
                },
                meta: {
                  requestId: 'req_8f3c1a2b4d5e6f70',
                  timestamp: '2026-09-03T18:20:00.000Z',
                },
              }),
            },
            405: {
              description: 'The path exists but not for this verb. Carries an `Allow` header.',
              content: jsonContent(responseSchema(errorResponseSchema)),
            },
            413: {
              description: 'Body over 4 KB.',
              content: jsonContent(responseSchema(errorResponseSchema)),
            },
            415: {
              description: 'Body sent as something other than `application/json`.',
              content: jsonContent(responseSchema(errorResponseSchema)),
            },
            429: {
              description:
                'Rate limit exceeded. Deliberately does **not** fall back to curated ' +
                'suggestions: 429 is a signal to slow down.',
              headers: {
                'Retry-After': {
                  description: 'Seconds until the window resets.',
                  schema: { type: 'integer' },
                },
                'RateLimit-Limit': { schema: { type: 'integer' } },
                'RateLimit-Remaining': { schema: { type: 'integer' } },
                'RateLimit-Reset': { schema: { type: 'integer' } },
              },
              content: jsonContent(responseSchema(errorResponseSchema), {
                error: {
                  code: 'RATE_LIMITED',
                  message: 'Too many requests. Please try again later.',
                  details: { retryAfterSeconds: 143 },
                },
                meta: {
                  requestId: 'req_8f3c1a2b4d5e6f70',
                  timestamp: '2026-09-03T18:20:00.000Z',
                },
              }),
            },
            500: {
              description:
                'Unexpected failure. Never carries a stack trace, a provider name or an ' +
                'upstream message.',
              content: jsonContent(responseSchema(errorResponseSchema)),
            },
          },
        },
      },
      '/health': {
        get: {
          tags: ['Health'],
          summary: 'Liveness',
          description:
            'Never checks the LLM provider: a health check that depends on a third ' +
            'party makes an orchestrator restart a healthy service during someone ' +
            "else's incident.",
          responses: {
            200: {
              description: 'The process is up.',
              content: jsonContent(
                {
                  type: 'object',
                  properties: {
                    status: { type: 'string', enum: ['ok'] },
                    uptimeSeconds: { type: 'integer' },
                    version: { type: 'string' },
                    llmProvider: { type: 'string' },
                  },
                  required: ['status', 'uptimeSeconds', 'version', 'llmProvider'],
                },
                { status: 'ok', uptimeSeconds: 42, version: '1.0.0', llmProvider: 'openai' },
              ),
            },
          },
        },
      },
    },
  };
}
